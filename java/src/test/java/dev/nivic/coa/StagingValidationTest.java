  /**
   * Step 4: Concurrent multi-user scenarios.
   */
  @Test
  void step4_ConcurrentMultiUserLoad() throws Exception {
    System.out.println("\n╔════════════════════════════════════════════════╗");
    System.out.println("║ PHASE 3 STAGING: Step 4 - Multi-user Load     ║");
    System.out.println("╚════════════════════════════════════════════════╝");

    step3_ExecuteTransactions();

    int numUsers = 10;
    int transactionsPerUser = 50;
    ExecutorService executor = Executors.newFixedThreadPool(numUsers);
    CountDownLatch latch = new CountDownLatch(numUsers);
    AtomicLong successCount = new AtomicLong(0);
    AtomicLong errorCount = new AtomicLong(0);

    long startTime = System.currentTimeMillis();

    for (int user = 0; user < numUsers; user++) {
      final int userId = user;
      executor.submit(() -> {
        try (Connection conn = getConnection();
             PreparedStatement psTrans = conn.prepareStatement(
                 "INSERT INTO coa_trans (ref_id, memo) VALUES (?, ?)",
                 Statement.RETURN_GENERATED_KEYS);
             PreparedStatement psData = conn.prepareStatement(
                 "INSERT INTO coa_trans_data (trans_id, line_no, account_code, debit_minor, credit_minor, party_mid) VALUES (?, ?, ?, ?, ?, ?)")) {

          for (int t = 0; t < transactionsPerUser; t++) {
            String ref = String.format("USER-%d-TXN-%d", userId, t);
            psTrans.setString(1, ref);
            psTrans.setString(2, "User " + userId + " transaction " + t);

            psTrans.executeUpdate();
            try (ResultSet rs = psTrans.getGeneratedKeys()) {
              if (rs.next()) {
                long transId = rs.getLong(1);

                // Insert debit line (2110 User Wallets debit 100k)
                psData.setLong(1, transId);
                psData.setInt(2, 1);
                psData.setString(3, "2110");
                psData.setLong(4, 100000);
                psData.setLong(5, 0);
                psData.setLong(6, (long) userId + 100);
                psData.executeUpdate();

                // Insert credit line (1111 Bank Account credit 100k) - double-entry
                psData.setLong(1, transId);
                psData.setInt(2, 2);
                psData.setString(3, "1111");
                psData.setLong(4, 0);
                psData.setLong(5, 100000);
                psData.setNull(6, java.sql.Types.BIGINT);
                psData.executeUpdate();

                successCount.incrementAndGet();
              }
            }
          }
        } catch (Exception e) {
          e.printStackTrace();
          errorCount.incrementAndGet();
        } finally {
          latch.countDown();
        }
      });
    }

    // Wait for completion
    boolean completed = latch.await(30, TimeUnit.SECONDS);
    long elapsedMs = System.currentTimeMillis() - startTime;
    executor.shutdown();

    System.out.println("✅ Multi-user test completed");
    System.out.println("   Users: " + numUsers);
    System.out.println("   Txns/user: " + transactionsPerUser);
    System.out.println("   Success: " + successCount.get());
    System.out.println("   Errors: " + errorCount.get());
    System.out.println("   Elapsed: " + elapsedMs + "ms");
    System.out.println("   Throughput: " + String.format("%.0f", (successCount.get() * 1000.0 / elapsedMs)) + " txns/sec");

    assert completed : "Test timed out";
    assert errorCount.get() == 0 : "Had " + errorCount.get() + " errors";
  }

  /**
   * Step 5: Generate reports and validate consistency.
   */
  @Test
  void step5_GenerateReportsValidateConsistency() throws Exception {
    System.out.println("\n╔════════════════════════════════════════════════╗");
    System.out.println("║ PHASE 3 STAGING: Step 5 - Reports & Validate  ║");
    System.out.println("╚════════════════════════════════════════════════╝");

    step4_ConcurrentMultiUserLoad();

    try (Connection conn = getConnection();
         Statement stmt = conn.createStatement()) {

      // Report 1: Account Balances
      System.out.println("\n📊 Account Balances:");
      try (ResultSet rs = stmt.executeQuery("""
          SELECT code, name, balance_minor
          FROM coa_account
          ORDER BY code
          """)) {
        while (rs.next()) {
          String code = rs.getString(1);
          String name = rs.getString(2);
          long balance = rs.getLong(3);
          System.out.println(String.format("   %s %-20s %,d", code, name, balance));
        }
      }

      // Report 2: Transaction Count by Type
      System.out.println("\n📊 Transaction Summary:");
      try (ResultSet rs = stmt.executeQuery("""
          SELECT COUNT(*) as txn_count, COUNT(DISTINCT ref_id) as unique_refs
          FROM coa_trans
          """)) {
        rs.next();
        System.out.println("   Total transactions: " + rs.getLong(1));
        System.out.println("   Unique refs: " + rs.getLong(2));
      }

      // Report 3: Validate Double-Entry Invariant
      System.out.println("\n📊 Double-Entry Validation:");
      try (ResultSet rs = stmt.executeQuery("""
          SELECT trans_id,
                 SUM(CASE WHEN debit_minor > 0 THEN debit_minor ELSE 0 END) as total_debit,
                 SUM(CASE WHEN credit_minor > 0 THEN credit_minor ELSE 0 END) as total_credit
          FROM coa_trans_data
          GROUP BY trans_id
          HAVING SUM(CASE WHEN debit_minor > 0 THEN debit_minor ELSE 0 END) !=
                 SUM(CASE WHEN credit_minor > 0 THEN credit_minor ELSE 0 END)
          """)) {
        int unbalancedCount = 0;
        while (rs.next()) {
          unbalancedCount++;
        }
        System.out.println("   Unbalanced transactions: " + unbalancedCount);
        assert unbalancedCount == 0 : "Found unbalanced transactions!";
      }

      // Report 4: Wallet Balances (Subsidiary Ledger)
      System.out.println("\n📊 Subsidiary Ledger (User Wallets):");
      try (ResultSet rs = stmt.executeQuery("""
          SELECT party_mid,
                 SUM(CASE WHEN credit_minor > 0 THEN credit_minor ELSE 0 END) -
                 SUM(CASE WHEN debit_minor > 0 THEN debit_minor ELSE 0 END) as wallet_balance
          FROM coa_trans_data
          WHERE account_code = '2110' AND party_mid IS NOT NULL
          GROUP BY party_mid
          ORDER BY party_mid
          """)) {
        int walletCount = 0;
        while (rs.next()) {
          long mid = rs.getLong(1);
          long balance = rs.getLong(2);
          System.out.println(String.format("   User %d: %,d", mid, balance));
          walletCount++;
        }
        System.out.println("   Total users with wallets: " + walletCount);
      }

      System.out.println("\n✅ All reports generated successfully");
      System.out.println("✅ Double-entry invariant validated");
    }
  }

