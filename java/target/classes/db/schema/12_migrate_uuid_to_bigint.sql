-- Step 1: Create new tables with BIGINT ID
CREATE TABLE IF NOT EXISTS coa_trans_new (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref_id     VARCHAR(128) UNIQUE,
  memo       VARCHAR(512),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS coa_trans_data_new (
  trans_id      BIGINT      NOT NULL REFERENCES coa_trans_new(id),
  line_no       SMALLINT    NOT NULL,
  account_code  VARCHAR(10) NOT NULL REFERENCES coa_account(code),
  debit_minor   BIGINT      NOT NULL DEFAULT 0,
  credit_minor  BIGINT      NOT NULL DEFAULT 0,
  currency_code VARCHAR(3)  NOT NULL DEFAULT 'VND',
  party_mid     BIGINT,
  PRIMARY KEY (trans_id, line_no)
);

CREATE TABLE IF NOT EXISTS coa_proposal_new (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_ref  VARCHAR(128) UNIQUE NOT NULL,
  maker_id     VARCHAR(100) NOT NULL,
  proposed_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  checker_id   VARCHAR(100),
  reviewed_at  TIMESTAMPTZ,
  status       VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
  reason       TEXT
);

-- Step 2: Copy data with UUID→BIGINT mapping
-- Note: In production, need to build a mapping of old UUID → new BIGINT IDs
-- For now, using a placeholder approach (assumes sequential IDs)

-- First, get the max ID from existing data to start the sequence
WITH uuid_to_id AS (
  SELECT
    old_uuid.id as old_id,
    ROW_NUMBER() OVER (ORDER BY old_uuid.created_at) as new_id
  FROM coa_trans old_uuid
)
INSERT INTO coa_trans_new (id, ref_id, memo, created_at)
SELECT
  utoi.new_id,
  t.ref_id,
  t.memo,
  t.created_at
FROM coa_trans t
JOIN uuid_to_id utoi ON utoi.old_id = t.id
ORDER BY utoi.new_id;

-- Step 3: Copy transaction lines
WITH uuid_to_id AS (
  SELECT
    old_uuid.id as old_id,
    ROW_NUMBER() OVER (ORDER BY old_uuid.created_at) as new_id
  FROM coa_trans old_uuid
)
INSERT INTO coa_trans_data_new (trans_id, line_no, account_code, debit_minor, credit_minor, currency_code, party_mid)
SELECT
  utoi.new_id,
  td.line_no,
  td.account_code,
  td.debit_minor,
  td.credit_minor,
  td.currency_code,
  td.party_mid
FROM coa_trans_data td
JOIN coa_trans t ON t.id = td.trans_id
JOIN uuid_to_id utoi ON utoi.old_id = t.id
ORDER BY utoi.new_id, td.line_no;

-- Step 4: Copy proposals
WITH uuid_to_id AS (
  SELECT
    old_uuid.id as old_id,
    ROW_NUMBER() OVER (ORDER BY old_uuid.created_at) as new_id
  FROM coa_proposal old_uuid
)
INSERT INTO coa_proposal_new (id, request_ref, maker_id, proposed_at, checker_id, reviewed_at, status, reason)
SELECT
  utoi.new_id,
  p.request_ref,
  p.maker_id,
  p.proposed_at,
  p.checker_id,
  p.reviewed_at,
  p.status,
  p.reason
FROM coa_proposal p
JOIN uuid_to_id utoi ON utoi.old_id = p.id
ORDER BY utoi.new_id;

