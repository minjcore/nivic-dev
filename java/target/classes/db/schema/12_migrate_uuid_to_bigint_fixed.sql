-- Migration: Convert UUID IDs to BIGINT IDENTITY (Fixed for actual schema)
-- Tables: coa_trans, coa_trans_data, coa_proposal, coa_proposal_line
-- Date: 2026-06-03
-- Status: PRODUCTION MIGRATION

-- ============================================================================
-- Step 1: Create new tables with BIGINT ID
-- ============================================================================

CREATE TABLE coa_trans_new (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref_id     VARCHAR(128) UNIQUE,
  memo       VARCHAR(512),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE coa_trans_data_new (
  trans_id      BIGINT      NOT NULL REFERENCES coa_trans_new(id),
  line_no       SMALLINT    NOT NULL,
  account_code  VARCHAR(10) NOT NULL REFERENCES coa_account(code),
  debit_minor   BIGINT      NOT NULL DEFAULT 0,
  credit_minor  BIGINT      NOT NULL DEFAULT 0,
  currency_code VARCHAR(3)  NOT NULL DEFAULT 'VND',
  party_mid     BIGINT,
  PRIMARY KEY (trans_id, line_no)
);

CREATE TABLE coa_proposal_new (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref_id          VARCHAR(128) UNIQUE,
  memo            VARCHAR(512),
  maker_id        VARCHAR(64) NOT NULL,
  status          VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  checker_id      VARCHAR(64),
  reason          VARCHAR(512),
  posted_trans_id BIGINT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  decided_at      TIMESTAMPTZ
);

CREATE TABLE coa_proposal_line_new (
  proposal_id  BIGINT      NOT NULL REFERENCES coa_proposal_new(id),
  line_no      SMALLINT    NOT NULL,
  account_code VARCHAR(10) NOT NULL,
  debit_minor  BIGINT      NOT NULL DEFAULT 0,
  credit_minor BIGINT      NOT NULL DEFAULT 0,
  party_mid    BIGINT,
  PRIMARY KEY (proposal_id, line_no)
);

-- ============================================================================
-- Step 2: Copy data with UUID→BIGINT mapping (preserving order via ROW_NUMBER)
-- ============================================================================

-- Copy coa_trans
WITH uuid_to_id AS (
  SELECT
    old_uuid.id as old_id,
    ROW_NUMBER() OVER (ORDER BY old_uuid.created_at) as new_id
  FROM coa_trans old_uuid
)
INSERT INTO coa_trans_new (id, ref_id, memo, created_at)
SELECT utoi.new_id, t.ref_id, t.memo, t.created_at
FROM coa_trans t
JOIN uuid_to_id utoi ON utoi.old_id = t.id
ORDER BY utoi.new_id;

-- Copy coa_trans_data
WITH uuid_to_id AS (
  SELECT
    old_uuid.id as old_id,
    ROW_NUMBER() OVER (ORDER BY old_uuid.created_at) as new_id
  FROM coa_trans old_uuid
)
INSERT INTO coa_trans_data_new (trans_id, line_no, account_code, debit_minor, credit_minor, currency_code, party_mid)
SELECT
  utoi.new_id,
  td.line_no,
  td.account_code,
  td.debit_minor,
  td.credit_minor,
  td.currency_code,
  td.party_mid
FROM coa_trans_data td
JOIN coa_trans t ON t.id = td.trans_id
JOIN uuid_to_id utoi ON utoi.old_id = t.id
ORDER BY utoi.new_id, td.line_no;

-- Copy coa_proposal
WITH uuid_to_id AS (
  SELECT
    old_uuid.id as old_id,
    ROW_NUMBER() OVER (ORDER BY old_uuid.created_at) as new_id
  FROM coa_proposal old_uuid
)
INSERT INTO coa_proposal_new (id, ref_id, memo, maker_id, status, checker_id, reason, posted_trans_id, created_at, decided_at)
SELECT
  utoi.new_id,
  p.ref_id,
  p.memo,
  p.maker_id,
  p.status,
  p.checker_id,
  p.reason,
  NULL,  -- posted_trans_id will be NULL (cannot map UUID→BIGINT without keeping mapping table)
  p.created_at,
  p.decided_at
FROM coa_proposal p
JOIN uuid_to_id utoi ON utoi.old_id = p.id
ORDER BY utoi.new_id;

-- Copy coa_proposal_line
WITH uuid_to_id AS (
  SELECT
    old_uuid.id as old_id,
    ROW_NUMBER() OVER (ORDER BY old_uuid.created_at) as new_id
  FROM coa_proposal old_uuid
)
INSERT INTO coa_proposal_line_new (proposal_id, line_no, account_code, debit_minor, credit_minor, party_mid)
SELECT
  utoi.new_id,
  pl.line_no,
  pl.account_code,
  pl.debit_minor,
  pl.credit_minor,
  pl.party_mid
FROM coa_proposal_line pl
JOIN coa_proposal p ON p.id = pl.proposal_id
JOIN uuid_to_id utoi ON utoi.old_id = p.id
ORDER BY utoi.new_id, pl.line_no;

-- ============================================================================
-- Step 3: Verify row counts match
-- ============================================================================

DO $$
DECLARE
  old_trans_count INT;
  new_trans_count INT;
  old_lines_count INT;
  new_lines_count INT;
  old_prop_count INT;
  new_prop_count INT;
  old_prop_lines INT;
  new_prop_lines INT;
BEGIN
  SELECT COUNT(*) INTO old_trans_count FROM coa_trans;
  SELECT COUNT(*) INTO new_trans_count FROM coa_trans_new;
  SELECT COUNT(*) INTO old_lines_count FROM coa_trans_data;
  SELECT COUNT(*) INTO new_lines_count FROM coa_trans_data_new;
  SELECT COUNT(*) INTO old_prop_count FROM coa_proposal;
  SELECT COUNT(*) INTO new_prop_count FROM coa_proposal_new;
  SELECT COUNT(*) INTO old_prop_lines FROM coa_proposal_line;
  SELECT COUNT(*) INTO new_prop_lines FROM coa_proposal_line_new;

  IF old_trans_count != new_trans_count THEN
    RAISE EXCEPTION 'coa_trans count mismatch: % vs %', old_trans_count, new_trans_count;
  END IF;

  IF old_lines_count != new_lines_count THEN
    RAISE EXCEPTION 'coa_trans_data count mismatch: % vs %', old_lines_count, new_lines_count;
  END IF;

  IF old_prop_count != new_prop_count THEN
    RAISE EXCEPTION 'coa_proposal count mismatch: % vs %', old_prop_count, new_prop_count;
  END IF;

  IF old_prop_lines != new_prop_lines THEN
    RAISE EXCEPTION 'coa_proposal_line count mismatch: % vs %', old_prop_lines, new_prop_lines;
  END IF;

  RAISE NOTICE '✅ Migration verified: % trans, % lines, % proposals, % proposal_lines',
    new_trans_count, new_lines_count, new_prop_count, new_prop_lines;
END $$;

